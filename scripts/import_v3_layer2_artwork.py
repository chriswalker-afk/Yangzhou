#!/usr/bin/env python3
"""Verify the *actual* user-uploaded V3 Layer 2 WebP artwork.

Run from the repository: python scripts/import_v3_layer2_artwork.py
The prepared original lossless WebPs were uploaded directly to the PR branch.
Historical original PNG masters remain preserved separately, not claimed as
repository binaries. Never substitute an autogenerated image for a missing file.
"""
from pathlib import Path
import hashlib
import sys

ROOT = Path(__file__).resolve().parents[1]
EXPECTED = {
    "willow-tree-01.webp": {
        "size": 2044912,
        "sha256": "8e41982dd8d59a5476d5430cb865d9f86578bb69e9bc69c94c30373d5392fc9e",
        "width": 1214, "height": 1229,
    },
    "garden-rockery-01.webp": {
        "size": 1223626,
        "sha256": "3a22cb438726d4a88cd9d24d6cf9be47faabd7ecff3aa604a9d3b5d131580e89",
        "width": 1238, "height": 815,
    },
}


def verify(path, spec):
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if len(data) != spec["size"] or digest != spec["sha256"]:
        raise ValueError(f"{path}: uploaded artwork does not match approved candidate hash/size")
    if data[:4] != b"RIFF" or data[8:16] != b"WEBPVP8L" or data[20] != 0x2F:
        raise ValueError(f"{path}: expected transparent lossless WebP VP8L")
    packed = int.from_bytes(data[21:25], "little")
    width, height = (packed & 0x3FFF) + 1, ((packed >> 14) & 0x3FFF) + 1
    alpha = (packed >> 28) & 1
    if (width, height, alpha) != (spec["width"], spec["height"], 1):
        raise ValueError(f"{path}: wrong artwork dimensions or missing alpha transparency")
    print(f"Verified {path.relative_to(ROOT)}: {width}x{height}, SHA-256 {digest}")


def main():
    if len(sys.argv) != 1:
        raise SystemExit("Usage: python scripts/import_v3_layer2_artwork.py")
    for name, spec in EXPECTED.items():
        verify(ROOT / "assets" / "v3" / "large" / name, spec)
    print("Both uploaded Layer 2 artwork binaries verified (not production-approved).")


if __name__ == "__main__":
    main()
